// generatedFields are the seven fields of the generated half, in the order a
// manifest writes them (ADR-048 decision 1).
var generatedFields = []string{"uses", "provides", "registers", "hooks", "configSchema", "durable", "requires"}

// Marker heads the generated half (07-c4-plugin-sdk.md:102). Parity never reads it.
const Marker = "--- generated by plugingen from the Spec; CI fails on a difference ---"

// Rewrite returns src, a plugin.yaml, with its generated half set to g: every other
// field and every comment are kept, and the seven fields follow them in order under
// the marker (ADR-048 decision 1).
func Rewrite(src []byte, g plugin.Generated) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("plugin.yaml: %w", err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, errors.New("plugin.yaml: not one mapping")
	}
	top := doc.Content[0]
	var kept []*yaml.Node
	for i := 0; i+1 < len(top.Content); i += 2 {
		if !slices.Contains(generatedFields, top.Content[i].Value) {
			kept = append(kept, top.Content[i], top.Content[i+1])
		}
	}
	for _, n := range kept {
		dropMarker(n)
	}
	gen, err := generatedNodes(g)
	if err != nil {
		return nil, err
	}
	gen[0].HeadComment = "# " + Marker
	top.Content = append(kept, gen...)
	var out bytes.Buffer
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, err
	}
	return out.Bytes(), enc.Close()
}

// dropMarker removes the marker from the comments of n and below, where an earlier
// rewrite left it.
func dropMarker(n *yaml.Node) {
	for _, c := range []*string{&n.HeadComment, &n.LineComment, &n.FootComment} {
		var lines []string
		for _, l := range strings.Split(*c, "\n") {
			if strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "#")) != Marker {
				lines = append(lines, l)
			}
		}
		*c = strings.TrimSpace(strings.Join(lines, "\n"))
	}
	for _, k := range n.Content {
		dropMarker(k)
	}
}

// generatedNodes encodes g as key and value nodes: each entry of a set in flow style
// on its own line, configSchema as a block mapping, the versions of requires in flow
// style.
func generatedNodes(g plugin.Generated) ([]*yaml.Node, error) {
	values := []any{g.Uses, g.Provides, g.Registers, g.Hooks, g.ConfigSchema, g.Durable, g.Requires}
	var out []*yaml.Node
	for i, v := range values {
		var n yaml.Node
		if err := n.Encode(v); err != nil {
			return nil, err
		}
		if n.Kind == yaml.SequenceNode {
			for _, e := range n.Content {
				e.Style = yaml.FlowStyle
			}
		}
		if generatedFields[i] == "requires" {
			for j := 0; j+1 < len(n.Content); j += 2 {
				if n.Content[j].Value == "definitions" {
					for _, list := range n.Content[j+1].Content {
						list.Style = yaml.FlowStyle
					}
				}
			}
		}
		out = append(out, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: generatedFields[i]}, &n)
	}
	return out, nil
}

// Parity reads src with boot's strict mode, the reading of plugin check (ADR-048
// decision 15), and compares its generated half, as read, with g, naming each field
// that differs. A comment, a layout and a hand-written field never fail it (ADR-048
// decision 1; 08-profiles-roadmap-adrs.md:1257).
func Parity(src []byte, g plugin.Generated) error {
	m, err := boot.ReadManifest("plugin.yaml", src, boot.ManifestStrict)
	if err != nil {
		return err
	}
	have, want := jsonFields(m), jsonFields(g)
	var errs []error
	for _, f := range generatedFields {
		name := strings.ToUpper(f[:1]) + f[1:] // the Go name of the field in both types
		if have[name] != want[name] {
			errs = append(errs, fmt.Errorf("%s: the file holds %s, plugingen writes %s", f, have[name], want[name]))
		}
	}
	return errors.Join(errs...)
}

// jsonFields returns each field of v, a boot.Manifest or a plugin.Generated, as JSON
// by its Go name, so that an int64 and a float64 of one value and the key order of a
// map compare equal. The two types name and order the fields alike, which a test of
// this package holds.
func jsonFields(v any) map[string]string {
	b, _ := json.Marshal(v) // never fails: the values are JSON data
	var fields map[string]json.RawMessage
	_ = json.Unmarshal(b, &fields)
	out := make(map[string]string, len(fields))
	for k, raw := range fields {
		out[k] = string(raw)
	}
	return out
}
