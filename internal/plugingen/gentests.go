// goLiteral writes v, a parsed config tree, as a Go literal of the tree types the
// launcher hands a plugin: nil, bool, int64, float64, string, []any and
// map[string]any.
func goLiteral(v any) (string, error) {
	switch x := v.(type) {
	case nil:
		return "nil", nil
	case bool:
		return strconv.FormatBool(x), nil
	case int64:
		return fmt.Sprintf("int64(%d)", x), nil
	case float64:
		return fmt.Sprintf("float64(%s)", strconv.FormatFloat(x, 'g', -1, 64)), nil
	case string:
		return strconv.Quote(x), nil
	case []any:
		var parts []string
		for _, e := range x {
			s, err := goLiteral(e)
			if err != nil {
				return "", err
			}
			parts = append(parts, s)
		}
		return "[]any{" + strings.Join(parts, ", ") + "}", nil
	case map[string]any:
		var parts []string
		for _, k := range slices.Sorted(maps.Keys(x)) {
			s, err := goLiteral(x[k])
			if err != nil {
				return "", err
			}
			parts = append(parts, strconv.Quote(k)+": "+s)
		}
		return "map[string]any{" + strings.Join(parts, ", ") + "}", nil
	}
	return "", fmt.Errorf("%v of type %T is not a literal config value; a reference has no resolver in the cycle test", v, v)
}
