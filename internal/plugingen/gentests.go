// cycleTest writes zz_cycle_test.go: cycle.Run on the plugin with the fake of each
// definition its Spec injects, the registries it lists and the row config of
// testdata/cycle.yaml, if any (ADR-060 decision 12). The plugin is imported as
// zzplugin, a name that neither testing, the runner nor a fake, <definition>fake,
// takes, whatever the plugin's package is called; like the file's name, it marks
// what plugingen owns, so a hand-written test of the package declares no such name.
func cycleTest(t target, fakes []Definition, registers []string, config string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by plugingen from the Spec of %s; DO NOT EDIT.\n", t.ID)
	b.WriteString("// The cycle test of 07-c4-plugin-sdk.md:1436 (ADR-060 decision 12).\n\n")
	fmt.Fprintf(&b, "package %s_test\n\nimport (\n\t\"testing\"\n\n", t.Name)
	fmt.Fprintf(&b, "\tzzplugin %q\n", t.ImportPath)
	for _, d := range fakes {
		fmt.Fprintf(&b, "\t%sfake %q\n", ident(d), d.Path+"/fake")
	}
	fmt.Fprintf(&b, "\t%q\n)\n\nfunc TestCycle(t *testing.T) {\n", modPath+"/sdk/testkit/cycle")
	for _, d := range fakes {
		fmt.Fprintf(&b, "\t%[1]sFake, %[1]sPlugin := %[1]sfake.New()\n", ident(d))
	}
	reg := "nil"
	if len(registers) > 0 {
		reg = fmt.Sprintf("%#v", registers)
	}
	fmt.Fprintf(&b, "\tcycle.Run(t, zzplugin.%s, %s, %s,\n", t.Accessor, config, reg)
	for _, d := range fakes {
		fmt.Fprintf(&b, "\t\tcycle.Fake{Plugin: %[1]sPlugin, Inventory: %[1]sFake.Inventory},\n", ident(d))
	}
	b.WriteString("\t)\n}\n")
	return format.Source([]byte(b.String()))
}

// ident names the fake of d in a cycle test: the definition's name, with its major
// above 0, so that two majors of one definition get two names.
func ident(d Definition) string {
	if d.Major == 0 {
		return d.Name
	}
	return d.Name + "v" + strconv.Itoa(d.Major)
}

