// registries are the registries whose suite a pack's rows can feed, each with what the
// Contribution of its suite takes after the fiber: the fixtures directory of commands
// (ADR-061 decision 5).
// ponytail: the three registries of S2a at major 0; a registry joins with its suite.
var registries = map[string]string{"commands": ", fixtures", "echoers": "", "stampers": ""}

// echoScenario is the binary of the echo scenario (ADR-060 decision 49).
const echoScenario = "scenario-echo"

// SuiteBinaries are the test binaries that a release's aiopsctl embeds under suites/,
// each <name>.test: the suite of each registry, then the echo scenario (ADR-060 decision
// 46).
func SuiteBinaries() []string {
	return append(sortedKeys(registries), echoScenario)
}

// SuitePlugin is a first-party instantiable plugin that the suite binaries run a pack's
// rows on: its package, its accessor, Plugin or New(), and the registries it feeds.
type SuitePlugin struct {
	Package, Accessor string
	Registers         []string
}

// SuitesGo returns the test files of the suite binaries by path under the scratch
// module, suites/<name>/: each runs, through internal/packsuite, the suite of a
// registry at its revision of revisions, or the echo scenario, on the rows of a pack
// that feed it, each with the plugin of ps that it names.
func SuitesGo(revisions map[string]int, ps []SuitePlugin) map[string][]byte {
	var imports string
	var vs []string
	for i, p := range ps {
		imports += fmt.Sprintf("\tp%d %q\n", i, p.Package)
		vs = append(vs, fmt.Sprintf("packsuite.Instantiable{Plugin: p%d.%s, Feeds: %#v}", i, p.Accessor, p.Registers))
	}
	values := strings.Join(vs, ", ")
	const head = "// Code generated by aiopsctl dist build. DO NOT EDIT.\n\n"
	out := map[string][]byte{}
	for reg, args := range registries {
		out["suites/"+reg+"/suite_test.go"] = fmt.Appendf(nil, head+`// The suite binary of %[1]s: the obligations of its suite on the rows of a pack (ADR-060
// decision 46).
package suite

import (
	"os"
	"testing"

	"%[2]s/internal/packsuite"
	"%[2]s/sdk/def/%[1]s/v0/conformance"
	"%[2]s/sdk/kernel"
	"%[2]s/sdk/testkit/kerneltest"
%[3]s)

func TestMain(m *testing.M) { os.Exit(packsuite.Main(m)) }

func TestPack(t *testing.T) {
	packsuite.Suite(t, %[1]q, %[4]d, conformance.Obligations, packsuite.Table(%[5]s), func(t *testing.T, p kernel.Plugin, config any, fixtures string) {
		conformance.Run(t, func(t *testing.T) (conformance.Subject, *kernel.Root) {
			root := kerneltest.New(t)
			return conformance.Contribution(root.Plugin(p, config)%[6]s), root
		})
	})
}
`, reg, rootModule, imports, revisions[reg], values, args)
	}
	out["suites/"+echoScenario+"/scenario_test.go"] = fmt.Appendf(nil, head+`// The binary of the echo scenario: each row of a pack called through the echoers
// dispatcher, replayed from its fixtures (ADR-060 decision 49).
package scenario

import (
	"os"
	"testing"

	"%[1]s/internal/packsuite"
	echoers "%[1]s/sdk/def/echoers/v0"
	"%[1]s/sdk/def/echoers/v0/fake"
	"%[1]s/sdk/kernel"
	"%[1]s/sdk/testkit/kerneltest"
%[2]s)

func TestMain(m *testing.M) { os.Exit(packsuite.Main(m)) }

func TestScenario(t *testing.T) {
	packsuite.Echo(t, packsuite.Table(%[3]s), func(t *testing.T) (*kernel.Root, echoers.Registry, kernel.Plugin) {
		reg, p := fake.New()
		return kerneltest.New(t), reg, p
	})
}
`, rootModule, imports, values)
	return out
}

// suites returns the test files of the suite binaries of a release build: the
// revision of each registry's suite from its definition.yaml in the zip of the SDK
// module, and in the second phase the first-party instantiable plugins of the module
// table, which the manifest of the first phase records, read from the zip of the root
// module.
func (b *build) suites() (map[string][]byte, error) {
	sdk := module.Version{Path: rootModule + "/sdk", Version: b.q.Root}
	z, err := zip.OpenReader(b.zip(sdk))
	if err != nil {
		return nil, fmt.Errorf("module %s: %w", sdk, err)
	}
	defer z.Close()
	revisions := map[string]int{}
	for reg := range registries {
		name := sdk.String() + "/def/" + reg + "/v0/definition.yaml"
		i := slices.IndexFunc(z.File, func(f *zip.File) bool { return f.Name == name })
		if i < 0 {
			return nil, fmt.Errorf("module %s holds no %s", sdk, name)
		}
		data, err := readZip(z.File[i])
		var d plugingen.Definition
		if err == nil {
			d, err = plugingen.ParseDefinition(sdk.Path+"/def/"+reg+"/v0", data)
		}
		if err != nil {
			return nil, err
		}
		revisions[reg] = d.Suite
	}
	var ps []SuitePlugin
	if s := b.q.Signed; s != nil {
		d, err := boot.ReadDistribution("the manifest of the first phase", s.Manifest)
		var table []tablePlugin
		if err == nil {
			table, err = tablePackages(b.zip(module.Version{Path: rootModule, Version: b.q.Root}), rootModule, b.q.Root)
		}
		if err != nil {
			return nil, err
		}
		for _, p := range table {
			m, err := boot.ReadManifest(p.pkg+"/plugin.yaml", p.manifest, boot.ManifestLenient)
			if err != nil || !m.Instantiable || !strings.HasPrefix(m.ID, "aiops/") || d.Plugins[m.ID].Package != p.pkg {
				continue
			}
			sp := SuitePlugin{Package: p.pkg, Accessor: p.accessor}
			for _, k := range m.Registers {
				sp.Registers = append(sp.Registers, k.Key)
			}
			ps = append(ps, sp)
		}
	}
	return SuitesGo(revisions, ps), nil
}

// compileSuites compiles, with g, each suite binary into the directory of the scratch
// aiopsctl that its main embeds, and returns the package graph of each.
func (b *build) compileSuites(ctx context.Context, g Go) ([][]Package, error) {
	var graphs [][]Package
	for _, name := range SuiteBinaries() {
		out := filepath.Join(b.scratch, "cmd", "aiopsctl", "suites", name+".test")
		if _, err := g.Run(ctx, "test", "-c", "-trimpath", "-tags=grpcnotrace", "-o", out, "./suites/"+name); err != nil {
			return nil, err
		}
		pkgs, err := b.graph(ctx, "./suites/"+name, "-test")
		if err != nil {
			return nil, err
		}
		graphs = append(graphs, pkgs)
	}
	return graphs, nil
}

// union returns the packages of graphs, each once.
func union(graphs ...[]Package) []Package {
	var out []Package
	seen := map[string]bool{}
	for _, g := range graphs {
		for _, p := range g {
			if !seen[p.ImportPath] {
				seen[p.ImportPath] = true
				out = append(out, p)
			}
		}
	}
	return out
}

