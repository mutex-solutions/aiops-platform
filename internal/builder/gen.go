// layout writes the OCI image layout res.Image: the server image, the files of aiops/
// of the output directory, tagged latest; and its referrer, the signed manifest, which
// dist sign signs and dist use verifies (ADR-044 decisions 1, 6 and 18). For the second
// phase of a release it also writes the builder image from the release aiopsctl of
// aiopsctl/, whose graph is ctl with the licences cl, tagged builder, and the referrer is
// the release artifact: the manifest with its bundle, annotated with the builder image's
// digest (ADR-044 decision 1; ADR-020 decision 13).
func (b *build) layout(ctx context.Context, res Result, ctl []Package, cl Licences, created time.Time) error {
	s, err := oci.NewWithContext(ctx, res.Image)
	y := layer{}
	if err == nil {
		err = y.tree(filepath.Join(b.q.Out, "aiops"), "")
	}
	var img ocispec.Descriptor
	if err == nil {
		img, err = pushImage(ctx, s, y, ocispec.ImageConfig{Entrypoint: []string{"/aiops"}})
	}
	if err == nil {
		err = s.Tag(ctx, img, "latest")
	}
	var bundle []byte
	notes := map[string]string{}
	if sg := b.q.Signed; sg != nil && err == nil {
		var bld ocispec.Descriptor
		bld, err = builderImage(ctx, s, sg.Definition, b.goroot, filepath.Join(b.q.Out, "aiopsctl"), ctl, cl, created)
		if err == nil {
			err = s.Tag(ctx, bld, "builder")
		}
		bundle, notes[BuilderAnnotation] = sg.Bundle, bld.Digest.String()
	}
	if err != nil {
		return err
	}
	return referrer(ctx, s, img, res.Manifest, bundle, notes)
}
