// siteGo returns the package site of the scratch module: the module table of the
// release, dist.Modules, then each plugin of the site with the manifest of its module,
// and the signed manifest that both binaries embed (07:1344; ADR-020 decision 12). It
// holds no init and no plugin of its own.
func siteGo(plugins []tablePlugin) []byte {
	var imports, embeds, entries bytes.Buffer
	for i, p := range plugins {
		fmt.Fprintf(&imports, "\tp%d %q\n", i, p.pkg)
		fmt.Fprintf(&embeds, "//go:embed manifests/%d.yaml\nvar m%d []byte\n\n", i, i)
		fmt.Fprintf(&entries, "\t\tdist.Module{Plugin: p%d.%s, Manifest: m%d},\n", i, p.accessor, i)
	}
	return fmt.Appendf(nil, `// Code generated by aiopsctl dist build. DO NOT EDIT.

// Package site is the module table of the distribution that dist build wrote.
package site

import (
	_ "embed"

	"github.com/mutex-solutions/aiops-platform/boot"
	"github.com/mutex-solutions/aiops-platform/dist"
%s)

// Signed is the signed distribution manifest of the build.
//
//go:embed distribution.yaml
var Signed []byte

%s// Modules is the module table: the release's, then the site's plugins.
func Modules() []dist.Module {
	return append(dist.Modules(),
%s	)
}

// Load returns the registry, the signed manifest and the release's limits.
func Load() (boot.Registry, []byte, boot.Limits, error) {
	_, _, lim, err := dist.Load()
	if err != nil {
		return boot.Registry{}, nil, boot.Limits{}, err
	}
	reg, err := dist.Table(Modules()...)
	return reg, Signed, lim, err
}
`, imports.String(), embeds.String(), entries.String())
}

