// epoch is the creation time every manifest of the image records, so that one build
// writes one digest.
const epoch = "1970-01-01T00:00:00Z"

// image writes the OCI image layout dir: an image for linux/amd64 with no base layer
// (ADR-044 decision 18), whose one layer holds the files of root, the server binary
// aiops with its THIRD_PARTY_LICENSES/, NOTICE and SBOM, tagged latest; and the signed
// manifest as its referrer of operations.DistributionType, which dist sign signs and
// dist use verifies (ADR-044 decision 1).
func image(ctx context.Context, dir, root string, manifest []byte) error {
	var layer bytes.Buffer
	tw := tar.NewWriter(&layer)
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || p == root {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		h := &tar.Header{Name: filepath.ToSlash(rel), Mode: 0o644, Typeflag: tar.TypeReg, Format: tar.FormatPAX}
		var data []byte
		switch {
		case d.IsDir():
			h.Name, h.Mode, h.Typeflag = h.Name+"/", 0o755, tar.TypeDir
		case rel == "aiops":
			h.Mode = 0o755
			fallthrough
		default:
			if data, err = os.ReadFile(p); err != nil {
				return err
			}
			h.Size = int64(len(data))
		}
		if err := tw.WriteHeader(h); err != nil {
			return err
		}
		_, err = tw.Write(data)
		return err
	})
	if err = errors.Join(err, tw.Close()); err != nil {
		return err
	}
	s, err := oci.NewWithContext(ctx, dir)
	if err != nil {
		return err
	}
	ld := content.NewDescriptorFromBytes(ocispec.MediaTypeImageLayer, layer.Bytes())
	rootfs := ocispec.RootFS{Type: "layers"}
	rootfs.DiffIDs = append(rootfs.DiffIDs, ld.Digest)
	cfg, _ := json.Marshal(ocispec.Image{Platform: ocispec.Platform{Architecture: "amd64", OS: "linux"},
		Config: ocispec.ImageConfig{Entrypoint: []string{"/aiops"}}, RootFS: rootfs})
	cd := content.NewDescriptorFromBytes(ocispec.MediaTypeImageConfig, cfg)
	md := content.NewDescriptorFromBytes(operations.DistributionLayer, manifest)
	for _, b := range []struct {
		d    ocispec.Descriptor
		data []byte
	}{{ld, layer.Bytes()}, {cd, cfg}, {md, manifest}} {
		if err := s.Push(ctx, b.d, bytes.NewReader(b.data)); err != nil {
			return err
		}
	}
	created := map[string]string{ocispec.AnnotationCreated: epoch}
	img, err := oras.PackManifest(ctx, s, oras.PackManifestVersion1_1, "", oras.PackManifestOptions{Layers: []ocispec.Descriptor{ld}, ConfigDescriptor: &cd, ManifestAnnotations: created})
	if err == nil {
		err = s.Tag(ctx, img, "latest")
	}
	if err == nil {
		_, err = oras.PackManifest(ctx, s, oras.PackManifestVersion1_1, operations.DistributionType, oras.PackManifestOptions{Subject: &img, Layers: []ocispec.Descriptor{md}, ManifestAnnotations: created})
	}
	return err
}
