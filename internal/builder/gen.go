// siteGo returns the package site of the scratch module: the module table, plugins,
// each with the manifest of its module, the release's then the site's, and the signed
// manifest that both binaries embed (07:1344; ADR-020 decision 12); for
// the second phase of a release, the release key's id, keyID, with the key and the
// bundle of the manifest (ADR-020 decision 13). It holds no init and no plugin of its
// own.
func siteGo(plugins []tablePlugin, keyID string) []byte {
	release := ""
	if keyID != "" {
		release = fmt.Sprintf(" = &boot.Release{KeyID: %q, Key: Key, Bundle: Bundle}", keyID)
	}
	var imports, embeds, entries bytes.Buffer
	for i, p := range plugins {
		fmt.Fprintf(&imports, "\tp%d %q\n", i, p.pkg)
		fmt.Fprintf(&embeds, "//go:embed manifests/%d.yaml\nvar m%d []byte\n\n", i, i)
		fmt.Fprintf(&entries, "\t\tdist.Module{Plugin: p%d.%s, Manifest: m%d},\n", i, p.accessor, i)
	}
	return fmt.Appendf(nil, `// Code generated by aiopsctl dist build. DO NOT EDIT.

// Package site is the module table of the distribution that dist build wrote.
package site

import (
	_ "embed"

	"github.com/mutex-solutions/aiops-platform/boot"
	"github.com/mutex-solutions/aiops-platform/dist"
%s)

// Signed is the signed distribution manifest of the build.
//
//go:embed distribution.yaml
var Signed []byte

// Key and Bundle are the release public key and the bundle of Signed that a release
// binary embeds, empty in a site's (ADR-020 decision 13).
//
//go:embed release.pub
var Key []byte

//go:embed distribution.bundle
var Bundle []byte

// Release is the release key with its id, the default distribution root of a release
// binary, with Signed its built-in record, and the bundle of Signed; nil in a site's.
var Release *boot.Release%s

%s// Modules is the module table: the release's, then the site's plugins.
func Modules() []dist.Module {
	return []dist.Module{
%s	}
}

// Load returns the registry, the signed manifest and the release's limits.
func Load() (boot.Registry, []byte, boot.Limits, error) {
	_, _, lim, err := dist.Load()
	if err != nil {
		return boot.Registry{}, nil, boot.Limits{}, err
	}
	reg, err := dist.Table(Modules()...)
	return reg, Signed, lim, err
}
`, imports.String(), release, embeds.String(), entries.String())
}

